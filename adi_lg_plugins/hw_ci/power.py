def choices_for(name: str) -> list[str]:
    """Dynamic choice lists, read from the installed labgrid."""
    if name == "network_power_models":
        import pkgutil

        import labgrid.driver.power as backends

        return sorted(m.name for m in pkgutil.iter_modules(backends.__path__))
    raise KeyError(name)


def types_in(category: str) -> list[PowerType]:
    return [t for t in POWER_TYPES.values() if t.category == category]


def by_driver(driver: str) -> PowerType | None:
    """Power type for a ``power-driver`` place tag (relay types share one driver)."""
    return next((t for t in POWER_TYPES.values() if t.driver == driver), None)


def _value(f: PowerField) -> str:
    var = f.var
    if f.kind == "int":
        return f"{{{{ {var} | default({f.default}) }}}}" if f.default else f"{{{{ {var} }}}}"
    if f.kind == "bool":
        return f"{{{{ ({var} | default('{f.default}')) | lower }}}}"
    if f.kind == "pairs":
        return (
            f"[{{% for p in ({var} | default('')).split(',') if p.strip() %}}"
            "[{{ p.split(':')[0] | trim | tojson }}, {{ p.split(':', 1)[1] | trim | tojson }}]"
            "{{ ', ' if not loop.last }}{% endfor %}]"
        )
    if f.default is not None:
        if f.default == "":
            return f"{{{{ {var} | default(none) | tojson }}}}"
        return f"{{{{ {var} | default({f.default!r}) | tojson }}}}"
    return f'"{{{{ {var} }}}}"'


def fragment(power: PowerType) -> str:
    """Exporter YAML fragment (Jinja) for this power type, indented into a group."""
    header = (
        f"## Power fragment: {power.label} ({power.key}), included by the stock exporter\n"
        "## templates. Generated from adi_lg_plugins/hw_ci/power.py - edit there, then run\n"
        "## `python -m adi_lg_plugins.hw_ci.power exporter_configs/templates/power`.\n"
    )
    if power.exporter_cls is None:
        return header + "## Nothing to export: the client uses ManualPowerDriver.\n"
    lines = [f"  {power.exporter_cls}:", f"    cls: {power.exporter_cls}"]
    for f in power.fields:
        if f.kind == "match":
            lines += [f"    {f.param}:", f'      ID_PATH: "{{{{ {f.var} }}}}"']
        else:
            lines.append(f"    {f.param}: {_value(f)}")
    for c in power.credentials:
        lines.append(f"    {c.param}: '{{{{ env[\"{c.env}\"] }}}}'")
    return header + "\n".join(lines) + "\n"


def write_fragments(directory) -> list[str]:
    from pathlib import Path

    out = Path(directory)
    out.mkdir(parents=True, exist_ok=True)
    for power in POWER_TYPES.values():
        (out / f"{power.key}.yaml").write_text(fragment(power))
    return sorted(POWER_TYPES)


