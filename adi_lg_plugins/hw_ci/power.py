"""Power-control types for generated lab configs.

One entry per way a lab board's power can be switched, covering this
package's outlets and upstream labgrid's power resources. Everything that
generates or consumes a power configuration reads from here:

- ``exporter_configs/templates/power/<key>.yaml`` - the exporter resource
  fragment each stock template includes (generated by :func:`fragment`, kept
  in sync by tests).
- ``adi-lg netbox add-hardware`` - the power prompts, the place's
  ``power-driver`` / ``power-output-driver`` tags, and credential checks.
- ``adi-lg-hw-ci render-env`` - which client driver(s) a place's tags select.

``coordinator/api/app/env_gen.py`` can't import this package, so it keeps its
own resource -> driver map; a test checks it against :data:`POWER_TYPES`.

Deliberately not offered (no exporter resource to describe):
``ExternalPowerDriver`` (runs commands on the client), ``FileDigitalOutputDriver``,
``SerialPortDigitalOutputDriver`` (toggles a line on the console's own serial
port), ``ManualSwitchDriver``, and ``DockerDriver`` / ``QEMUDriver`` (virtual
targets, not board power).
"""

from __future__ import annotations

from dataclasses import dataclass

# Categories, in the order they are offered.
PDU = "Network PDU"
PLUG = "Smart plug / home automation"
USB = "USB-switched port"
RELAY = "Relay / digital output"
SUPPLY = "Bench power supply"
OTHER = "Other"
CATEGORIES = (PDU, PLUG, USB, RELAY, SUPPLY, OTHER)


@dataclass(frozen=True)
class PowerField:
    """One resource parameter the operator supplies.

    ``kind`` controls how the value is written: ``str``, ``int``, ``bool``,
    ``match`` (a udev ``ID_PATH`` match mapping) or ``pairs`` (comma-separated
    ``a:b`` items, written as a list of two-item lists).
    ``default`` of ``None`` means required.
    ``scope`` says what the value describes when NetBox records the board's
    power: ``device`` identifies the power device, ``outlet`` picks the outlet
    on it, ``board`` is a setting of this board's connection only.
    """

    var: str
    param: str
    prompt: str
    kind: str = "str"
    default: str | None = None
    choices: str | None = None  # name of a dynamic choice list (see choices_for)
    scope: str = "device"


@dataclass(frozen=True)
class PowerCredential:
    """A secret parameter read from the exporter's environment, never written to the file."""

    param: str
    env: str
    required: bool = True


@dataclass(frozen=True)
class PowerType:
    key: str
    category: str
    label: str
    package: str  # "adi_lg_plugins" or "labgrid"
    driver: str  # client PowerProtocol driver - the place's `power-driver` tag
    exporter_cls: str | None = None  # None: nothing to export (manual)
    client_cls: str | None = None  # class a client sees after labgrid exports it
    output_driver: str | None = None  # DigitalOutputProtocol driver under DigitalOutputPowerDriver
    fields: tuple[PowerField, ...] = ()
    credentials: tuple[PowerCredential, ...] = ()
    reach: str = "exporter"  # host that must reach the device: "exporter" or "client"
    note: str = ""

    @property
    def drivers(self) -> tuple[str, ...]:
        """Client drivers, in the order labgrid must create them."""
        return (self.output_driver, self.driver) if self.output_driver else (self.driver,)

    @property
    def outlet_field(self) -> PowerField | None:
        """The field that picks the outlet; None for a single switch (one outlet)."""
        return next((f for f in self.fields if f.scope == "outlet"), None)

    @property
    def device_fields(self) -> tuple[PowerField, ...]:
        """The fields that identify the power device itself."""
        return tuple(f for f in self.fields if f.scope == "device")


def _f(var, param, prompt, kind="str", default=None, choices=None, scope="device"):
    return PowerField(f"power_{var}", param, prompt, kind, default, choices, scope)


def _outlet(var, param, prompt, kind="str", default=None):
    return _f(var, param, prompt, kind, default, scope="outlet")


_USB_PATH = _f("usb_path", "match", "udev ID_PATH of the USB device", "match")
_INVERT = _f("invert", "invert", "Invert output (true/false)", "bool", "false", scope="board")
_HOST = _f("host", "host", "Device hostname or IP")


def _relay(key, label, exporter_cls, output_driver, fields, client_cls=None, note=""):
    return PowerType(
        key,
        RELAY,
        label,
        "labgrid",
        "DigitalOutputPowerDriver",
        exporter_cls,
        client_cls or exporter_cls,
        output_driver,
        fields,
        note=note,
    )


